// Convert string into 2D Boolean grid (matrix)
export function stringToMatrix(text: string): boolean[][] {
  const upper = text.toUpperCase();
  const rows = 7;
  const charWidth = 5;
  const spacing = 1;

  const totalWidth = upper.length * (charWidth + spacing);
  const matrix: boolean[][] = Array.from({ length: rows }, () =>
    Array(totalWidth).fill(false)
  );

  let colOffset = 0;
  for (let i = 0; i < upper.length; i++) {
    const char = upper[i];
    const bitmap = FONT_5X7[char] || FONT_5X7[" "];

    for (let r = 0; r < rows; r++) {
      const byte = bitmap[r] || 0;
      for (let c = 0; c < charWidth; c++) {
        // Bit 4 is leftmost in a 5-bit width
        const bit = (byte >> (4 - c)) & 1;
        if (bit === 1) {
          matrix[r][colOffset + c] = true;
        }
      }
    }
    colOffset += charWidth + spacing;
  }

  return matrix;
}

// Convert 2D matrix into ASCII art text (like the screenshot 8888 8888 blocks)
export function matrixToAsciiText(
  matrix: boolean[][],
  charFilled = "88",
  charEmpty = "  "
): string {
  return matrix
    .map((row) =>
      row.map((cell) => (cell ? charFilled : charEmpty)).join("")
    )
    .join("\n");
}

// Helper to convert any text directly to ASCII string banner
export function textToAsciiBanner(text: string, style: "88" | "##" | "@@" | "::" = "88"): string {
  const matrix = stringToMatrix(text);
  const fillMap = {
    "88": "88",
    "##": "##",
    "@@": "@@",
    "::": "::",
  };
  return matrixToAsciiText(matrix, fillMap[style], "  ");
}
